import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { practiceByLesson } from '../src/practice.js';
const session = `sql-workshop-${Date.now()}`;
const browser = (...args) => execFileSync('npx', ['--yes', 'agent-browser', '--session', session, ...args], { encoding: 'utf8', timeout: 60000 }).trim();
const evaluate = expression => JSON.parse(browser('eval', expression));
const click = selector => { browser('scrollintoview', selector); browser('click', selector); };
const query = sql => { browser('focus', '.cm-content'); browser('keyboard', 'inserttext', sql); browser('press', 'Control+Enter'); };
const workshop = () => { click('#workshop'); click('#resume-practice'); if (evaluate('Boolean(document.querySelector("#story-player[open]"))')) click('#story-skip'); browser('wait', '#craft-query'); };
mkdirSync('artifacts/practice', { recursive: true });
try {
  browser('open', process.argv[2] || 'http://127.0.0.1:4173');
  browser('wait', '#story-player[open]'); click('#story-skip'); click('#story-skip'); click('#skip-teaching');
  const progressBefore = evaluate('localStorage.getItem("sql-wizard-progress-v5")');
  workshop();
  assert.equal(evaluate('document.querySelectorAll("[data-problem]").length'), 3);
  query('SELECT 123;'); browser('wait', '#craft-feedback.mismatch');
  assert.equal(evaluate('document.querySelectorAll(".inventory-grid strong").length'), 0);
  click('#craft-reset');
  const first = practiceByLesson['first-spark'][0];
  query(first.solution); browser('wait', '#craft-feedback.success');
  assert.equal(evaluate('document.querySelectorAll(".inventory-grid strong").length'), 1);
  click('#craft-cast'); browser('wait', '#craft-feedback.success');
  assert.equal(evaluate('document.querySelectorAll(".inventory-grid strong").length'), 1);
  click('#craft-next');
  const second = practiceByLesson['first-spark'][1];
  for (const hint of second.hints) click('#craft-hint');
  query(second.solution); browser('wait', '#craft-feedback.success');
  assert.match(browser('get', 'text', '.inventory-grid'), /With a worked example/);
  browser('reload'); browser('wait', '#workshop'); workshop();
  assert.equal(evaluate('document.querySelectorAll(".inventory-grid strong").length'), 2);
  assert.equal(browser('get', 'text', '#craft-title'), second.title);
  click('#craft-cast'); browser('wait', '#craft-feedback.success');
  assert.match(browser('get', 'text', '[data-problem][aria-pressed="true"]'), /with an example/);
  click('#craft-reset'); query(second.solution); browser('wait', '#craft-feedback.success');
  assert.doesNotMatch(browser('get', 'text', '.inventory-grid'), /With a worked example/);
  click('[data-practice-stage="empty-shelves"]');
  query(practiceByLesson['empty-shelves'][0].solution); browser('wait', '#craft-feedback.success');
  browser('reload'); browser('wait', '#workshop'); workshop();
  assert.equal(browser('get', 'text', '#craft-title'), practiceByLesson['empty-shelves'][0].title);
  browser('set', 'viewport', '390', '844');
  assert.equal(evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  assert.equal(evaluate('[...document.images].every(img=>img.complete && img.naturalWidth>0)'), true);
  browser('screenshot', 'artifacts/practice/workshop-mobile.png', '--full');
  browser('set', 'viewport', '1440', '1000');
  browser('screenshot', 'artifacts/practice/workshop-desktop.png', '--full');
  click('#leave-workshop'); browser('wait', '#query');
  click('#workshop'); click('[data-practice-chapter="first-spark"]'); browser('wait', '#craft-query');
  assert.equal(browser('get', 'text', '#craft-title'), first.title);
  click('#leave-workshop'); browser('wait', '#query');
  const before = JSON.parse(progressBefore), after = JSON.parse(evaluate('localStorage.getItem("sql-wizard-progress-v5")'));
  assert.deepEqual(after.progress, before.progress); assert.deepEqual(after.learning, before.learning);
  assert.equal(browser('errors'), '');
  console.log('PASS workshop: wrong answer, independent/assisted crafts, no duplicate rewards, reload, fresh attempt, LEFT JOIN, mobile, lesson isolation, no browser errors');
} finally { browser('close'); }
